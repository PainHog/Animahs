#!/usr/bin/env node
/**
 * Second Nature rules simulator — CLI → sim/REPORT.md.
 *
 *   node sim/run.mjs                       # full report (default sizes)
 *   node sim/run.mjs --runs 4000 --balance 800 --sweep 800 --seed 1
 *   node sim/run.mjs --quick               # small runs, prints the summary only
 *   node sim/run.mjs --set startWild=3     # override a parameter (repeatable)
 *
 * Same seed and options → same report. Every table says how many runs it used.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { playMission } from "./engine.mjs";
import { MISSIONS } from "./scenarios.mjs";
import { makeParty, makeCharacter, validateParty } from "./character.mjs";
import { makeParams, PARAMS, PRESETS } from "./params.mjs";
import { makeRng } from "./rng.mjs";
import { Tally } from "./recorder.mjs";
import { pct, num, pts } from "./stats.mjs";
import * as R from "./rules-data.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const SIZES = [3, 4, 5];

/* ---------------- CLI ---------------- */
const argv = process.argv.slice(2);
const opt = { runs: 4000, balance: 800, sweep: 800, seed: 1, quick: false, out: join(HERE, "REPORT.md"), set: {} };
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--runs") opt.runs = +argv[++i];
  else if (a === "--balance") opt.balance = +argv[++i];
  else if (a === "--sweep") opt.sweep = +argv[++i];
  else if (a === "--seed") opt.seed = +argv[++i];
  else if (a === "--out") opt.out = argv[++i];
  else if (a === "--quick") { opt.quick = true; opt.runs = 1000; opt.balance = 0; opt.sweep = 0; }
  else if (a === "--set") { const [k, v] = argv[++i].split("="); opt.set[k] = JSON.parse(v); }
  else throw new Error(`unknown option ${a}`);
}
const BASE = makeParams(opt.set);

/* ---------------- running ---------------- */

function mainCell(m, size, N, params, seed) {
  const t = new Tally();
  for (let i = 0; i < N; i++) {
    const party = makeParty(makeRng(seed, "party", m.id, size, i), size);
    t.add(playMission(m, party, makeRng(seed, "dice", m.id, size, i), params));
  }
  return t;
}

/** Slot 0 forced to an option; others random; same dice per run index (common random numbers). */
function forcedCell(m, size, N, params, seed, force) {
  const t = new Tally();
  for (let i = 0; i < N; i++) {
    const c0 = makeCharacter(makeRng(seed, "slot0", m.id, size, i), 0, new Set(), force);
    const rngO = makeRng(seed, "others", m.id, size, i);
    const taken = new Set([c0.animal]);
    const party = [c0];
    for (let j = 1; j < size; j++) { const c = makeCharacter(rngO, j, taken); taken.add(c.animal); party.push(c); }
    validateParty(party);
    t.add(playMission(m, party, makeRng(seed, "dice", m.id, size, i), params));
  }
  return t;
}

function grid(fn) {
  const cells = {};
  for (const m of MISSIONS) for (const size of SIZES) cells[`${m.id}:${size}`] = fn(m, size);
  return cells;
}
const pool = (cells, pred) => Object.entries(cells).filter(([k]) => pred(k)).reduce((t, [, v]) => t.merge(v), new Tally());
const labelOf = id => MISSIONS.find(m => m.id === id).label;

/* ---------------- targets (DESIGN D22) ---------------- */
const TARGETS = {
  win: { easy: [0.85, 0.95], standard: [0.70, 0.80], hard: [0.50, 0.62] },
  loss: { easy: [0, 0.05], standard: [0.05, 0.15], hard: [0.12, 0.30] },
  huntUp: { easy: [0, 0.35], standard: [0.25, 0.50], hard: [0.45, 0.75] }, // revised by DESIGN D26
  takenHard: [0.3, 0.8],
  crit: [0.15, 0.25], fail: [0.08, 0.15],
  spentMedian: 0.5, shiftedOnce: 0.85, shifts: [1.2, 3.0], animalShare: [0.5, 0.8],
  balance: 0.04, perkValue: 0.015, perkSpread: 0.03, sizeSpread: 0.05, clashRounds: 3, clashRound4: 0.05,
};
const inR = (x, [lo, hi]) => x >= lo - 1e-9 && x <= hi + 1e-9;
const mark = ok => (ok ? "✓" : "✗");

/* ---------------- main ---------------- */
const t0 = Date.now();
const main = grid((m, s) => mainCell(m, s, opt.runs, BASE, opt.seed));
const byLabel = {};
for (const lab of R.LABEL_ORDER) {
  byLabel[lab] = { all: pool(main, k => labelOf(k.split(":")[0]) === lab).summary };
  for (const s of SIZES) byLabel[lab][s] = pool(main, k => labelOf(k.split(":")[0]) === lab && k.endsWith(`:${s}`)).summary;
}
const ALL = pool(main, () => true).summary;

const out = [];
const w = s => out.push(s);
const cmd = `node sim/run.mjs --runs ${opt.runs} --balance ${opt.balance} --sweep ${opt.sweep} --seed ${opt.seed}` +
  Object.entries(opt.set).map(([k, v]) => ` --set ${k}=${JSON.stringify(v)}`).join("");

w(`# Second Nature — simulator report (core rules v0.1b draft)`);
w("");
w(`Generated by \`${cmd}\`. Same command → same report. Rules: \`docs/CORE-RULES.md\`; missions: \`sim/scenarios.mjs\`; judgement calls: \`sim/params.mjs\` (defaults unless set above); method: \`sim/README.md\`.`);
w("");
w(`Every mission × party size (3, 4, 5) runs ${opt.runs} times with random legal characters (§11).`);
w("");

// ---- summary vs targets
const rows = [];
for (const lab of R.LABEL_ORDER) {
  const L = byLabel[lab].all;
  rows.push([`${lab} win`, pct(L.win), `${pct(TARGETS.win[lab][0], 0)}–${pct(TARGETS.win[lab][1], 0)}`, mark(inR(L.win, TARGETS.win[lab]))]);
  rows.push([`${lab} loss`, pct(L.loss), `${pct(TARGETS.loss[lab][0], 0)}–${pct(TARGETS.loss[lab][1], 0)}`, mark(inR(L.loss, TARGETS.loss[lab]))]);
  rows.push([`${lab} Hunt is Up`, pct(L.huntUp), `${pct(TARGETS.huntUp[lab][0], 0)}–${pct(TARGETS.huntUp[lab][1], 0)}`, mark(inR(L.huntUp, TARGETS.huntUp[lab]))]);
}
rows.push(["hard Taken / mission", num(byLabel.hard.all.taken), "0.30–0.80", mark(inR(byLabel.hard.all.taken, TARGETS.takenHard))]);
for (const lab of R.LABEL_ORDER) {
  const ws = SIZES.map(s => byLabel[lab][s].win);
  const spread = Math.max(...ws) - Math.min(...ws);
  rows.push([`${lab} win spread across 3/4/5 players`, `${pts(spread)} pts`, "≤ 5 pts", mark(spread <= TARGETS.sizeSpread + 1e-9)]);
}
rows.push(["Criticals (share of rolls)", pct(ALL.crit), "15–25%", mark(inR(ALL.crit, TARGETS.crit))]);
rows.push(["Fails (share of rolls)", pct(ALL.fail), "8–15%", mark(inR(ALL.fail, TARGETS.fail))]);
rows.push(["median share of Wild spent", pct(ALL.spentMedian, 0), "≥ 50%", mark(ALL.spentMedian >= TARGETS.spentMedian)]);
rows.push(["characters who shift at least once", pct(ALL.shiftedOnce), "≥ 85%", mark(ALL.shiftedOnce >= TARGETS.shiftedOnce)]);
rows.push(["shifts per character per mission", num(ALL.shifts), "1.2–3.0", mark(inR(ALL.shifts, TARGETS.shifts))]);
rows.push(["rolls made in animal form", pct(ALL.animalShare), "50–80%", mark(inR(ALL.animalShare, TARGETS.animalShare))]);
rows.push(["Clash length (rounds, mean)", num(ALL.clashRounds), "≤ 3", mark(ALL.clashRounds <= TARGETS.clashRounds)]);
rows.push(["Clashes reaching round 4", pct(ALL.clashRound4), "< 5%", mark(ALL.clashRound4 < TARGETS.clashRound4)]);

w(`## 1. Against the targets (DESIGN D22, Hunt-is-Up targets revised in D26)`);
w("");
w(`| Measure | Result | Target | |`);
w(`|---|---|---|---|`);
for (const r of rows) w(`| ${r.join(" | ")} |`);
w("");
const balanceRowsAt = out.length; // balance verdicts are inserted here later

// ---- by label × size
w(`## 2. Results by label and party size`);
w("");
w(`Win = objective done, nobody Taken. Costly = done, someone Taken. Loss = not done. "Up" = the Hunt was Up (Scent reached the Limit) at any point; "Up inside" = before the Escape.`);
w("");
w(`| Label | Players | Win | Costly | Loss | Taken / mission | Up | Up inside | Final Scent |`);
w(`|---|---|---|---|---|---|---|---|---|`);
for (const lab of R.LABEL_ORDER) for (const s of [...SIZES, "all"]) {
  const L = byLabel[lab][s];
  w(`| ${lab} | ${s} | ${pct(L.win)} | ${pct(L.costly)} | ${pct(L.loss)} | ${num(L.taken)} | ${pct(L.huntUp)} | ${pct(L.huntUpIn)} | ${num(L.scent, 1)} |`);
}
w("");
w(`### By mission`);
w("");
w(`| Mission | Label | Limit | Players | Win | Costly | Loss | Taken | Up | Clashes | Rolls |`);
w(`|---|---|---|---|---|---|---|---|---|---|---|`);
for (const m of MISSIONS) for (const s of SIZES) {
  const L = main[`${m.id}:${s}`].summary;
  const limit = m.limit[s] + (BASE.limitShift ?? 0) + (BASE.sizeLimit?.[s] ?? 0);
  w(`| ${m.name} | ${m.label} | ${limit} | ${s} | ${pct(L.win)} | ${pct(L.costly)} | ${pct(L.loss)} | ${num(L.taken)} | ${pct(L.huntUp)} | ${num(L.clashes, 1)} | ${num(L.rollsPerMission, 1)} |`);
}
w("");

// ---- dice, morphing, resources, clashes
w(`## 3. Dice, morphing, Wild and Clashes (all missions and sizes)`);
w("");
w(`| Measure | Value |`);
w(`|---|---|`);
w(`| rolls per mission | ${num(ALL.rollsPerMission, 1)} |`);
w(`| Fail · Partial · Success · Critical | ${pct(ALL.fail)} · ${pct(ALL.partial)} · ${pct(1 - ALL.fail - ALL.partial - ALL.crit)} · ${pct(ALL.crit)} |`);
w(`| shifts into animal form per character | ${num(ALL.shifts)} |`);
w(`| characters who shift at least once | ${pct(ALL.shiftedOnce)} |`);
w(`| rolls made in animal form | ${pct(ALL.animalShare)} |`);
w(`| characters Stuck in animal form / mission | ${num(ALL.stuck)} |`);
w(`| shifts paid for with Hurt (no Wild left) / mission | ${num(ALL.overdraws)} |`);
w(`| characters Exposed / mission | ${num(ALL.exposed)} |`);
w(`| median share of Wild spent · characters spending ≥ half | ${pct(ALL.spentMedian, 0)} · ${pct(ALL.spentHalf)} |`);
w(`| Pushes (paid · free) / mission | ${num(ALL.pushes)} · ${num(ALL.freePushes)} |`);
w(`| Helps / mission | ${num(ALL.helps)} |`);
w(`| Patch Ups / mission | ${num(ALL.patches)} |`);
w(`| Edges gained · used / mission | ${num(ALL.edgesGained)} · ${num(ALL.edgesUsed)} |`);
w(`| poor scouting rolls (Partial or Fail) | ${pct(ALL.scoutFail)} |`);
w(`| Clashes / mission · mean rounds · reaching round 4 | ${num(ALL.clashes)} · ${num(ALL.clashRounds)} · ${pct(ALL.clashRound4)} |`);
w(`| Down · Netted / mission | ${num(ALL.downs)} · ${num(ALL.nets)} |`);
w(`| obstacles that hit the 30-round safety stop / mission | ${num(ALL.maxRoundsHit, 3)} |`);
w("");

// ---- perk fire rates (dead content)
const allT = pool(main, () => true);
w(`### How often each perk changes a roll (per mission where a character has it)`);
w("");
w(`| Perk | Fires per mission | | Perk | Fires per mission |`);
w(`|---|---|---|---|---|`);
const fireRows = [
  ...R.ANIMAL_ORDER.map(a => [`${R.ANIMALS[a].name}: ${R.ANIMALS[a].perk}`, (allT.fires[a] ?? 0) / (allT.present[a] || 1)]),
  ...R.PERK_ORDER.map(p => [R.PERKS[p].name, (allT.fires[p] ?? 0) / (allT.present[p] || 1)]),
];
for (let i = 0; i < fireRows.length; i += 2) {
  const a = fireRows[i], b = fireRows[i + 1] ?? ["", NaN];
  w(`| ${a[0]} | ${num(a[1])} | | ${b[0]} | ${Number.isNaN(b[1]) ? "" : num(b[1])} |`);
}
w("");

// ---- balance
const findings = [];
if (opt.balance > 0) {
  const exp = (forces) => {
    const res = {};
    for (const [key, force] of forces) {
      const cells = grid((m, s) => forcedCell(m, s, opt.balance, BASE, opt.seed, force));
      res[key] = { all: pool(cells, () => true).summary };
      for (const lab of R.LABEL_ORDER) res[key][lab] = pool(cells, k => labelOf(k.split(":")[0]) === lab).summary;
      for (const m of MISSIONS) res[key][m.id] = pool(cells, k => k.startsWith(`${m.id}:`)).summary;
    }
    return res;
  };
  const frames = exp(R.FRAME_ORDER.map(f => [f, { frame: f }]));
  const animals = exp(R.ANIMAL_ORDER.map(a => [a, { animal: a }]));
  const perks = exp([...R.PERK_ORDER, "none"].map(p => [p, { perk: p }]));

  const meanOf = (res, keys, f = "all") => keys.reduce((a, k) => a + res[k][f].win, 0) / keys.length;
  w(`## 4. Balance (slot 0 forced to the option, the rest of the group random; ${opt.balance} runs per mission × size per option, same dice)`);
  w("");
  w(`Δ = that option's win rate minus the average of its peers, in points. Target: every frame and animal within ±4 points; every human perk at least +1.5 points better than having no perk, and within ±3 of the perk average.`);
  w("");
  w(`### Frames`);
  w("");
  w(`| Frame | Win (all) | Δ all | Δ easy | Δ standard | Δ hard | ${MISSIONS.map(m => m.id).join(" | ")} |`);
  w(`|---|---|---|---|---|---|${MISSIONS.map(() => "---").join("|")}|`);
  const fMean = Object.fromEntries(["all", ...R.LABEL_ORDER, ...MISSIONS.map(m => m.id)].map(f => [f, meanOf(frames, R.FRAME_ORDER, f)]));
  for (const f of R.FRAME_ORDER) {
    const d = x => frames[f][x].win - fMean[x];
    w(`| ${R.FRAMES[f].name} | ${pct(frames[f].all.win)} | ${pts(d("all"))} | ${pts(d("easy"))} | ${pts(d("standard"))} | ${pts(d("hard"))} | ${MISSIONS.map(m => pts(d(m.id))).join(" | ")} |`);
    if (Math.abs(d("all")) > TARGETS.balance) findings.push(`Frame **${R.FRAMES[f].name}** is ${pts(d("all"))} points from the frame average (target ±4).`);
  }
  w("");
  w(`### Animals (Δ against the average of all 18)`);
  w("");
  w(`| Animal | Frame | Win (all) | Δ all | Δ hard | Δ vs its frame-mates |`);
  w(`|---|---|---|---|---|---|`);
  const aMean = meanOf(animals, R.ANIMAL_ORDER), aMeanHard = meanOf(animals, R.ANIMAL_ORDER, "hard");
  for (const a of R.ANIMAL_ORDER) {
    const mates = R.animalsOf(R.ANIMALS[a].frame);
    const mateMean = meanOf(animals, mates);
    const d = animals[a].all.win - aMean;
    w(`| ${R.ANIMALS[a].name} (${R.ANIMALS[a].perk}) | ${R.FRAMES[R.ANIMALS[a].frame].name} | ${pct(animals[a].all.win)} | ${pts(d)} | ${pts(animals[a].hard.win - aMeanHard)} | ${pts(animals[a].all.win - mateMean)} |`);
    if (Math.abs(d) > TARGETS.balance) findings.push(`Animal **${R.ANIMALS[a].name}** is ${pts(d)} points from the animal average (target ±4).`);
  }
  w("");
  w(`### Human perks`);
  w("");
  w(`| Perk | Win (all) | Value vs no perk | Δ vs perk average | Value at hard |`);
  w(`|---|---|---|---|---|`);
  const pMean = meanOf(perks, R.PERK_ORDER);
  for (const p of [...R.PERK_ORDER, "none"]) {
    const val = perks[p].all.win - perks.none.all.win;
    const valH = perks[p].hard.win - perks.none.hard.win;
    const name = p === "none" ? "*(no perk: control)*" : R.PERKS[p].name;
    w(`| ${name} | ${pct(perks[p].all.win)} | ${p === "none" ? "—" : pts(val)} | ${p === "none" ? "—" : pts(perks[p].all.win - pMean)} | ${p === "none" ? "—" : pts(valH)} |`);
    if (p !== "none") {
      if (val < TARGETS.perkValue) findings.push(`Human perk **${R.PERKS[p].name}** is worth only ${pts(val)} points over no perk (target ≥ +1.5).`);
      if (Math.abs(perks[p].all.win - pMean) > TARGETS.perkSpread) findings.push(`Human perk **${R.PERKS[p].name}** is ${pts(perks[p].all.win - pMean)} points from the perk average (target ±3).`);
    }
  }
  w("");
}

// ---- spotlights: rolls per character by frame and mission
w(`## 5. Spotlights: rolls per character, by frame and mission (main runs)`);
w("");
w(`Shows where each frame does the work. A frame with a low number everywhere has no spotlight (A9).`);
w("");
{
  const spot = {};
  for (const m of MISSIONS) for (const s of SIZES) {
    for (let i = 0; i < Math.min(opt.runs, 1000); i++) {
      const party = makeParty(makeRng(opt.seed, "party", m.id, s, i), s);
      const r = playMission(m, party, makeRng(opt.seed, "dice", m.id, s, i), BASE);
      for (const c of r.chars) {
        const k = `${m.id}:${c.frame}`;
        spot[k] ??= { rolls: 0, n: 0, animal: 0 };
        spot[k].rolls += c.rollsAnimal + c.rollsHuman; spot[k].animal += c.rollsAnimal; spot[k].n++;
      }
    }
  }
  w(`| Frame | ${MISSIONS.map(m => m.id).join(" | ")} |`);
  w(`|---|${MISSIONS.map(() => "---").join("|")}|`);
  for (const f of R.FRAME_ORDER) {
    w(`| ${R.FRAMES[f].name} | ${MISSIONS.map(m => { const x = spot[`${m.id}:${f}`]; return x ? `${num(x.rolls / x.n, 1)} (${pct(x.animal / (x.rolls || 1), 0)} animal)` : "—"; }).join(" | ")} |`);
  }
  w("");
}

// ---- sweeps
if (opt.sweep > 0) {
  w(`## 6. Judgement calls and presets (${opt.sweep} runs per mission × size)`);
  w("");
  w(`Each row changes one parameter from its default (\`sim/params.mjs\`). Δ in points against the default row.`);
  w("");
  w(`| Variant | Easy win | Standard win | Hard win | Hard loss | Hard Taken | Up (all) | Wild spent (median) | Shifts / char |`);
  w(`|---|---|---|---|---|---|---|---|---|`);
  const variants = [["default", {}]];
  for (const [k, v] of Object.entries(PARAMS)) for (const alt of v.alts) variants.push([`${k} = ${JSON.stringify(alt)}`, { [k]: alt }]);
  for (const [k, v] of Object.entries(PRESETS)) if (k !== "default") variants.push([`preset: ${k}`, v]);
  let base = null;
  for (const [name, ov] of variants) {
    const params = makeParams({ ...opt.set, ...ov });
    const cells = grid((m, s) => mainCell(m, s, opt.sweep, params, opt.seed));
    const L = lab => pool(cells, k => labelOf(k.split(":")[0]) === lab).summary;
    const e = L("easy"), st = L("standard"), h = L("hard"), a = pool(cells, () => true).summary;
    if (!base) base = { e, st, h };
    const d = (x, b) => (name === "default" ? "" : ` (${pts(x - b)})`);
    w(`| ${name} | ${pct(e.win)}${d(e.win, base.e.win)} | ${pct(st.win)}${d(st.win, base.st.win)} | ${pct(h.win)}${d(h.win, base.h.win)} | ${pct(h.loss)} | ${num(h.taken)} | ${pct(a.huntUp)} | ${pct(a.spentMedian, 0)} | ${num(a.shifts)} |`);
  }
  w("");
}

// ---- findings
const fails = rows.filter(r => r[3] === "✗").map(r => `**${r[0]}** is ${r[1]} (target ${r[2]}).`);
const allFindings = [...fails, ...findings];
if (ALL.maxRoundsHit > 0) allFindings.push(`Some obstacles hit the 30-round safety stop (${num(ALL.maxRoundsHit, 3)} per mission): a rules gap.`);
const block = [`### Off-target`, "", ...(allFindings.length ? allFindings.map(f => `- ${f}`) : ["- Nothing: every measured target is met."]), ""];
out.splice(balanceRowsAt, 0, ...block);

const text = out.join("\n") + "\n";
if (opt.quick) console.log(text.split("## 3.")[0]);
else { writeFileSync(opt.out, text); console.log(`wrote ${opt.out} in ${((Date.now() - t0) / 1000).toFixed(0)} s`); console.log(text.split("## 2.")[0]); }
